import { S3Client, PutObjectCommand, DeleteObjectCommand, GetObjectCommand } from "@aws-sdk/client-s3";
import { getSignedUrl } from "@aws-sdk/s3-request-presigner";
import { config } from "dotenv"; config({ path: ".env.local", quiet: true });
const s3 = new S3Client({ region: process.env.AWS_REGION, endpoint: process.env.AWS_ENDPOINT_URL_S3, forcePathStyle: true });
const Bucket="images", Key="_probe/test.txt";
await s3.send(new PutObjectCommand({Bucket,Key,Body:"hi",ContentType:"text/plain"})); console.log("put ok");
const anon = `${process.env.AWS_ENDPOINT_URL_S3}/${Bucket}/${Key}`;
console.log("anonymous GET:", (await fetch(anon)).status);
const url = await getSignedUrl(s3, new GetObjectCommand({Bucket,Key}), {expiresIn:60});
const r = await fetch(url); console.log("signed GET:", r.status, await r.text());
await s3.send(new DeleteObjectCommand({Bucket,Key})); console.log("deleted");
